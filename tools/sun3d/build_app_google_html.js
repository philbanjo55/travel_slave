#!/usr/bin/env node
// Builds src/components/sun/sun3dGoogleHtml.ts: one self-contained page (app_view_google.js bundled with
// three.js 0.160 and 3d-tiles-renderer 0.3.31) for the app's web view, the "HD" picture of the 3D sun view.
//   node tools/sun3d/build_app_google_html.js <dir>
// <dir> holds node_modules from `npm i three@0.160.0 3d-tiles-renderer@0.3.31 esbuild`. Nothing comes from a CDN:
// the page fetches only Google's tiles (through the door in init's tiles.base) and the DRACO decoder (tiles.draco).
const fs = require('fs'), path = require('path');
const dir = path.resolve(process.argv[2] || '.'), mods = path.join(dir, 'node_modules');
const esbuild = require(path.join(mods, 'esbuild'));
const out = esbuild.buildSync({
  entryPoints: [path.join(__dirname, 'app_view_google.js')], bundle: true, format: 'iife', minify: true, target: 'es2020',
  nodePaths: [mods], write: false, legalComments: 'none', logLevel: 'warning', tsconfigRaw: '{}',
});
const app = out.outputFiles[0].text;
const safe = s => s.replace(/<\/script/gi, '<\\/script');
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>html,body{margin:0;height:100%;background:#111111;overflow:hidden}canvas{display:block;width:100%;height:100%;touch-action:none}
#msg{position:absolute;left:0;top:0;right:0;bottom:0;display:flex;align-items:center;justify-content:center;color:#888888;font:14px Roboto,system-ui,sans-serif;text-align:center;padding:16px;background:#111111}</style>
</head><body><canvas id="view"></canvas><div id="msg">Loading the terrain…</div>
<script>${safe(app)}</script></body></html>`;
const file = path.join(__dirname, '../../src/components/sun/sun3dGoogleHtml.ts');
fs.writeFileSync(file, `// Generated by tools/sun3d/build_app_google_html.js from tools/sun3d/app_view_google.js, three.js 0.160 and 3d-tiles-renderer 0.3.31. Do not edit.\n/* eslint-disable */\nexport const SUN3D_GOOGLE_HTML: string = ${JSON.stringify(html)};\n`);
if (process.argv[3]) fs.writeFileSync(process.argv[3], html);   // the same page as a file, for headless tests
console.log('wrote', file, Math.round(fs.statSync(file).size / 1024) + ' KB');
