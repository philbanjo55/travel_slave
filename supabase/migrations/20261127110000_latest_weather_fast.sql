-- latest_weather_per_stop, fast version (Phil, 27 Nov 2026: "Ya do it"). Same rows and columns as before: each stop's newest
-- forecast (trip-date rows first, then newest fetched), reported on the day that forecast row was fetched for. Before, the
-- database sorted the whole forecast table (16,700 rows) and only then kept the asked-for day: 1.3 s quiet, 14 s under
-- load, and it timed out Accept at 2:55 PM ET 27 Nov. Now the day's stops are found first (index on day_id) and each
-- stop's newest row is read on its own (index on stop_id): 61 ms. Checked before the swap: all 602 stops identical
-- (md5 of every column, display and score included). Undo: tools/sql/latest_weather_per_stop_before_20261127.sql.
create or replace view public.latest_weather_per_stop with (security_invoker = true) as
 SELECT l.id,
    c.stop_id,
    c.day_id,
    l.trip_id,
    l.fetched_at,
    l.forecast_valid_for,
    l.source,
    l.temperature_c,
    l.cloud_cover_pct,
    l.cloud_cover_low_pct,
    l.cloud_cover_mid_pct,
    l.cloud_cover_high_pct,
    l.precip_probability_pct,
    l.precip_mm,
    l.wind_speed_kmh,
    l.wind_gusts_kmh,
    l.wind_direction_deg,
    l.weather_code,
    l.sunrise,
    l.sunset,
    l.is_golden_hour,
    l.raw,
    l.created_at,
    l.apparent_temperature_c,
    l.relative_humidity_pct,
    l.dew_point_c,
    l.rain_mm,
    l.showers_mm,
    l.snowfall_cm,
    l.visibility_m,
    l.surface_pressure_hpa,
    l.is_day,
    l.uv_index,
    l.daylight_minutes,
    l.precip_hours,
    l.is_dark,
    l.fog_risk,
    l.score_stars,
    l.score_label,
    l.score_reason,
    l.score_components,
    l.cloud_base_m,
    l.cloud_top_m,
    l.cloud_cover_2m_pct,
    l.wave_height_m,
    l.wave_period_s,
    l.wave_direction_deg,
    l.swell_wave_height_m,
    l.swell_wave_period_s,
    l.wind_wave_height_m,
    l.sea_surface_temp_c,
    l.model_count,
    l.primary_model,
    l.horizon_hours,
    weather_display(ROW(l.id, l.stop_id, l.day_id, l.trip_id, l.fetched_at, l.forecast_valid_for, l.source, l.temperature_c, l.cloud_cover_pct, l.cloud_cover_low_pct, l.cloud_cover_mid_pct, l.cloud_cover_high_pct, l.precip_probability_pct, l.precip_mm, l.wind_speed_kmh, l.wind_gusts_kmh, l.wind_direction_deg, l.weather_code, l.sunrise, l.sunset, l.is_golden_hour, l.raw, l.created_at, l.apparent_temperature_c, l.relative_humidity_pct, l.dew_point_c, l.rain_mm, l.showers_mm, l.snowfall_cm, l.visibility_m, l.surface_pressure_hpa, l.is_day, l.uv_index, l.daylight_minutes, l.precip_hours, l.is_dark, l.fog_risk, l.score_stars, l.score_label, l.score_reason, l.score_components, l.cloud_base_m, l.cloud_top_m, l.cloud_cover_2m_pct, l.wave_height_m, l.wave_period_s, l.wave_direction_deg, l.swell_wave_height_m, l.swell_wave_period_s, l.wind_wave_height_m, l.sea_surface_temp_c, l.model_count, l.primary_model, l.horizon_hours)) AS display,
        CASE
            WHEN tr.archived IS TRUE OR tr.end_date IS NOT NULL AND tr.end_date < CURRENT_DATE THEN NULL::jsonb
            ELSE weather_score(ROW(l.id, l.stop_id, l.day_id, l.trip_id, l.fetched_at, l.forecast_valid_for, l.source, l.temperature_c, l.cloud_cover_pct, l.cloud_cover_low_pct, l.cloud_cover_mid_pct, l.cloud_cover_high_pct, l.precip_probability_pct, l.precip_mm, l.wind_speed_kmh, l.wind_gusts_kmh, l.wind_direction_deg, l.weather_code, l.sunrise, l.sunset, l.is_golden_hour, l.raw, l.created_at, l.apparent_temperature_c, l.relative_humidity_pct, l.dew_point_c, l.rain_mm, l.showers_mm, l.snowfall_cm, l.visibility_m, l.surface_pressure_hpa, l.is_day, l.uv_index, l.daylight_minutes, l.precip_hours, l.is_dark, l.fog_risk, l.score_stars, l.score_label, l.score_reason, l.score_components, l.cloud_base_m, l.cloud_top_m, l.cloud_cover_2m_pct, l.wave_height_m, l.wave_period_s, l.wave_direction_deg, l.swell_wave_height_m, l.swell_wave_period_s, l.wind_wave_height_m, l.sea_surface_temp_c, l.model_count, l.primary_model, l.horizon_hours), st.shot_type)
        END AS score
   FROM ( SELECT DISTINCT weather_forecasts.stop_id, weather_forecasts.day_id FROM weather_forecasts WHERE weather_forecasts.stop_id IS NOT NULL) c
     CROSS JOIN LATERAL ( SELECT w.id,
            w.stop_id,
            w.day_id,
            w.trip_id,
            w.fetched_at,
            w.forecast_valid_for,
            w.source,
            w.temperature_c,
            w.cloud_cover_pct,
            w.cloud_cover_low_pct,
            w.cloud_cover_mid_pct,
            w.cloud_cover_high_pct,
            COALESCE(w.precip_probability_pct, ( SELECT round((e.value ->> 'precip_probability_pct'::text)::numeric)::integer AS round
                   FROM jsonb_each(COALESCE(w.raw -> 'models'::text, '{}'::jsonb)) e(key, value)
                  WHERE (e.value ->> 'precip_probability_pct'::text) IS NOT NULL
                  ORDER BY ((e.value ->> 'resolution_km'::text)::numeric), ((e.value ->> 'distance_km'::text)::numeric), e.key
                 LIMIT 1), round(((((w.raw -> 'ensemble'::text) -> 'by_variable'::text) -> 'precipitation'::text) ->> 'prob_wet_pct'::text)::numeric)::integer) AS precip_probability_pct,
            w.precip_mm,
            w.wind_speed_kmh,
            w.wind_gusts_kmh,
            w.wind_direction_deg,
            w.weather_code,
            w.sunrise,
            w.sunset,
            w.is_golden_hour,
            w.raw,
            w.created_at,
            w.apparent_temperature_c,
            w.relative_humidity_pct,
            w.dew_point_c,
            w.rain_mm,
            w.showers_mm,
            w.snowfall_cm,
            w.visibility_m,
            w.surface_pressure_hpa,
            w.is_day,
            w.uv_index,
            w.daylight_minutes,
            w.precip_hours,
            w.is_dark,
            w.fog_risk,
            w.score_stars,
            w.score_label,
            w.score_reason,
            w.score_components,
            w.cloud_base_m,
            w.cloud_top_m,
            w.cloud_cover_2m_pct,
            w.wave_height_m,
            w.wave_period_s,
            w.wave_direction_deg,
            w.swell_wave_height_m,
            w.swell_wave_period_s,
            w.wind_wave_height_m,
            w.sea_surface_temp_c,
            w.model_count,
            w.primary_model,
            w.horizon_hours
           FROM weather_forecasts w
          WHERE w.stop_id = c.stop_id
          ORDER BY (((w.raw -> 'provenance'::text) ->> 'date_mode'::text) = 'trip-date'::text) DESC NULLS LAST, w.fetched_at DESC
         LIMIT 1) l
     LEFT JOIN stops st ON st.id = l.stop_id
     LEFT JOIN trips tr ON tr.id = l.trip_id
  WHERE l.day_id IS NOT DISTINCT FROM c.day_id;
